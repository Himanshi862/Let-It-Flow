"""
inspect_datasets.py  -  Let It Flow, Stage 1
--------------------------------------------
PURPOSE
    Read BOTH datasets *without changing them* and write a data-quality report.
    This script only LOOKS at the data. It does not train any model, does not
    fill in missing values, and does not merge the two datasets.

HOW TO RUN (from the let-it-flow/ folder)
    pip install pandas numpy openpyxl
    python inspect_datasets.py

OUTPUT (created in the data_reports/ folder)
    data_quality_report.md      <- human-readable report (open in VS Code / any editor)
    primary_interval_flags.csv  <- every primary-survey interval outside 18-45 days
    kaggle_missingness.csv      <- % missing for every Kaggle column
    kaggle_duplicates.csv       <- duplicate / conflicting Kaggle rows
"""

import os
import numpy as np
import pandas as pd

# ----------------------------------------------------------------------------
# 1. FILE LOCATIONS  (change these if you saved the files somewhere else)
# ----------------------------------------------------------------------------
PRIMARY_FILE = "datasets/primary_dataset/Primary_Data_Revised_Cycle_Cleaning.xlsx"
KAGGLE_FILE = "datasets/kaggle_dataset/2data.csv"
OUT_DIR = "data_reports"

# Broad "screening" range used ONLY to flag odd intervals for human review.
# It is NOT a medical definition and nothing is deleted because of it.
SCREEN_LOW, SCREEN_HIGH = 18, 45

os.makedirs(OUT_DIR, exist_ok=True)
lines = []  # we collect the report text here and write it at the end


def add(text=""):
    """Add one line to the report and also print it on screen."""
    print(text)
    lines.append(text)


def table(df, index=True):
    """Turn a DataFrame into a markdown table (plain text, no extra packages)."""
    d = df.reset_index() if index else df
    head = "| " + " | ".join(str(c) for c in d.columns) + " |"
    sep = "|" + "|".join("---" for _ in d.columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in d.itertuples(index=False)]
    return "\n".join([head, sep] + rows)


# ============================================================================
# 2. PRIMARY DATASET  (college-student survey, Excel workbook with 5 sheets)
# ============================================================================
add("# Let It Flow - Stage 1 Data-Quality Report")
add()
add("Generated by `inspect_datasets.py`. Nothing in the original files was changed.")
add()
add("---")
add("## PART A - PRIMARY DATASET (college student survey)")
add()

book = pd.ExcelFile(PRIMARY_FILE)
add(f"Sheets in workbook: {book.sheet_names}")
cohort = book.parse("Primary_Model_Cohort")      # 33 people kept by the cleaning
excluded = book.parse("Excluded_Misinterpreted")  # 4 people removed by the cleaning
audit = book.parse("All_Consented_Audit")         # all 37 consenting people
flags = book.parse("Quality_Flags")
readme = book.parse("Read_Me")

add()
add("### A1. What each sheet is")
add(f"- Primary_Model_Cohort: {cohort.shape[0]} rows x {cohort.shape[1]} columns")
add(f"- Excluded_Misinterpreted: {excluded.shape[0]} rows")
add(f"- All_Consented_Audit: {audit.shape[0]} rows")
add(f"- Quality_Flags: {flags.shape[0]} flag rows")
ids_ok = set(audit.participant_id) == set(cohort.participant_id) | set(excluded.participant_id)
add(f"- Cohort + Excluded = Audit (same participant IDs)? **{ids_ok}**")
add("- One ROW = ONE PARTICIPANT (one survey response). Repeated cycles are stored as")
add("  separate date COLUMNS (raw_date_1..4), not as repeated rows.")
add(f"- participant_id unique? **{cohort.participant_id.is_unique}**")

add()
add("### A2. Column names and data types (cohort sheet)")
dt = pd.DataFrame({"column": cohort.columns, "dtype": [str(t) for t in cohort.dtypes],
                   "missing": cohort.isna().sum().values})
add(table(dt, index=False))

add()
add("### A3. Cleaning decisions already made by the data owner (Read_Me sheet)")
for _, r in readme.iterrows():
    add(f"- **{r['topic']}**: {r['decision']}")

# --- intervals -------------------------------------------------------------
iv_cols = ["date_based_cycle_interval_1_days", "date_based_cycle_interval_2_days",
           "date_based_cycle_interval_3_days"]
iv = cohort[iv_cols]
all_iv = iv.stack().dropna()  # dropna: newer pandas keeps empty cells
n_iv = len(all_iv)
outside = all_iv[(all_iv < SCREEN_LOW) | (all_iv > SCREEN_HIGH)]

add()
add("### A4. Cycle intervals (date-based, cohort only)")
add(f"- Participants: {len(cohort)}")
n_int = iv.notna().sum(axis=1)
add(f"- Participants with exactly 1 interval: {(n_int == 1).sum()}, 2 intervals: {(n_int == 2).sum()}, "
    f"3 intervals: {(n_int == 3).sum()}")
add(f"- Total intervals: **{n_iv}**  (observed across ~4 months only)")
add(f"- Intervals inside {SCREEN_LOW}-{SCREEN_HIGH} days: {n_iv - len(outside)}; "
    f"outside: **{len(outside)}** (values: {sorted(outside.astype(int).tolist())})")
add(f"- Median interval: {all_iv.median():.0f} days; mean {all_iv.mean():.1f}; "
    f"SD {all_iv.std():.1f} (inflated by the odd values above)")
flag_rows = []
for col in iv_cols:
    bad = cohort[(cohort[col] < SCREEN_LOW) | (cohort[col] > SCREEN_HIGH)]
    for _, r in bad.iterrows():
        flag_rows.append({"participant_id": r.participant_id, "interval_column": col,
                          "days": int(r[col]),
                          "raw_dates": [str(d.date()) for d in
                                        r[["raw_date_1", "raw_date_2", "raw_date_3", "raw_date_4"]].dropna()]})
pd.DataFrame(flag_rows).to_csv(f"{OUT_DIR}/primary_interval_flags.csv", index=False)
add(f"- Participants with at least one out-of-range interval: "
    f"**{len({f['participant_id'] for f in flag_rows})}** of {len(cohort)} "
    f"(details saved in primary_interval_flags.csv)")
add("- Very small gaps (1, 2, 3, 5, 10 days) cannot be real period-to-period cycles. Possible causes (unconfirmed):")
add("  respondents typed period END dates or other dates, or mixed up the order. Only the")
add("  participants themselves could confirm; we must NOT correct them.")

# raw dates not in newest-to-oldest order
raw_cols = ["raw_date_1", "raw_date_2", "raw_date_3", "raw_date_4"]
unordered = []
for _, r in cohort.iterrows():
    vals = r[raw_cols].dropna().tolist()
    if vals != sorted(vals, reverse=True):
        unordered.append(r.participant_id)
add(f"- Participants whose raw dates were NOT typed newest-to-oldest: {unordered}")
add(f"- Participants with an exact repeated date: {(cohort.exact_duplicate_date_entries > 0).sum()}")
add(f"- Most recent period start range: {cohort.raw_date_1.min().date()} to {cohort.raw_date_1.max().date()}")

# self-reported vs observed
plaus = iv.where((iv >= SCREEN_LOW) & (iv <= SCREEN_HIGH))
obs_mean = plaus.mean(axis=1)
sr = cohort.self_reported_cycle_length_numeric_provisional
cmp = pd.DataFrame({"self_reported": sr, "observed_mean_plausible": obs_mean}).dropna()
add()
add(f"- Self-reported cycle length vs mean of plausible date-based intervals "
    f"({len(cmp)} participants): mean absolute difference = "
    f"**{(cmp.self_reported - cmp.observed_mean_plausible).abs().mean():.1f} days**.")
add("  (Descriptive only. Ranges such as '27-29' were turned into midpoints by the data owner.)")

# --- survey answers --------------------------------------------------------
add()
add("### A5. Participant characteristics (cohort, n=33)")
add(f"- Age: min {cohort.age_years.min()}, median {cohort.age_years.median():.0f}, "
    f"max {cohort.age_years.max()}; participants aged 18-24: "
    f"{((cohort.age_years >= 18) & (cohort.age_years <= 24)).sum()}")
for c in ["cycle_regularity", "symptom_severity", "dietary_preference", "preferred_exercise",
          "daily_activity_level", "bleeding_duration_raw"]:
    add(f"- **{c}**: " + "; ".join(f"{k} = {v}" for k, v in
                                    cohort[c].value_counts(dropna=False).items()))
mc = cohort.known_medical_conditions.notna().sum()
add(f"- known_medical_conditions: {mc} of {len(cohort)} wrote something "
    f"(self-reported; used for context only, never as a label to diagnose anyone)")

add()
add("### A6. Can the primary dataset train a prediction model?")
add(f"- Only {int((n_int >= 2).sum())} people have 2+ intervals and {int((n_int >= 3).sum())} have 3. "
    f"Total {n_iv} intervals from {len(cohort)} people, spanning one short window.")
add("- That is far too little for a supervised next-cycle model, and after the out-of-range")
add("  intervals are set aside it is even less. **Recommended role: describe the student")
add("  population, test the app's rules on realistic student data, and (at most) act as a")
add("  small external sanity-check set. NOT a training set.**")
add("- It has NO BMI, sleep, stress or exam-period fields, so the lifestyle module can only")
add("  use symptoms, diet, exercise and activity from here; richer lifestyle analysis must")
add("  come from app users over time.")

# ============================================================================
# 3. KAGGLE / FEDCYCLE DATASET
# ============================================================================
add()
add("---")
add("## PART B - KAGGLE / FedCycle DATASET")
add()

# Everything is read as text first because blanks make pandas guess 'object'.
raw = pd.read_csv(KAGGLE_FILE, dtype=str, keep_default_na=False)
k = raw.replace(r"^\s*$", np.nan, regex=True)   # blank strings -> real missing
num_fail = []
for c in k.columns:
    if c == "ClientID":
        continue
    conv = pd.to_numeric(k[c], errors="coerce")
    if conv.notna().sum() != k[c].notna().sum():   # some text could not be converted
        num_fail.append(c)
    k[c] = conv

add("### B1. Shape and what one row means")
add(f"- {k.shape[0]} rows x {k.shape[1]} columns; **{k.ClientID.nunique()} participants** (ClientID)")
add("- One ROW = ONE MENSTRUAL CYCLE of one participant (ClientID + CycleNumber).")
add("- So rows from the same participant are NOT independent -> split by ClientID.")
add(f"- Columns that could not be fully converted to numbers: {num_fail if num_fail else 'none'}")
add("- Most columns are numeric codes/measurements; 4 are free text (medication / surgery notes).")
add("- **No codebook was supplied**, so I")
add("  will not guess what coded values (Group, ReproductiveCategory, Maristatus, Religion,")
add("  Ethnicity, Method...) mean. Please send the data dictionary.")

cpc = k.groupby("ClientID").size()
add()
add("### B2. Repeated observations")
add(f"- Cycles per participant: min {cpc.min()}, median {cpc.median():.0f}, mean {cpc.mean():.1f}, max {cpc.max()}")
add(f"- Participants with < 4 cycles: {(cpc < 4).sum()}; with >= 4: {(cpc >= 4).sum()}; with >= 10: {(cpc >= 10).sum()}")

dup_full = k[k.duplicated(keep=False)]
dup_key = k[k.duplicated(["ClientID", "CycleNumber"], keep=False)].sort_values(["ClientID", "CycleNumber"])
pd.concat([dup_key.assign(kind="same ClientID+CycleNumber")]).to_csv(
    f"{OUT_DIR}/kaggle_duplicates.csv", index=False)
n_full = int(k.duplicated().sum())
n_key = int(k.duplicated(["ClientID", "CycleNumber"]).sum())
add()
add("### B3. Duplicates and numbering")
add(f"- Fully identical duplicate rows: **{n_full}**")
add(f"- Extra rows sharing the same ClientID + CycleNumber: **{n_key}** "
    f"({n_key - n_full} of them have DIFFERENT values = conflicting records; see kaggle_duplicates.csv)")
gaps = []
for cid, g in k.drop_duplicates().groupby("ClientID"):
    s = g.CycleNumber.sort_values().unique()
    if len(s) > 1 and (np.diff(s) != 1).any():
        gaps.append(cid)
add(f"- Participants whose CycleNumber sequence has gaps: {len(gaps)} {gaps}")

y = k.LengthofCycle
add()
add("### B4. Candidate target: LengthofCycle (days)")
add(f"- Missing: {y.isna().sum()}; min {y.min():.0f}, median {y.median():.0f}, mean {y.mean():.1f}, "
    f"SD {y.std():.1f}, max {y.max():.0f}")
add(f"- Cycles outside {SCREEN_LOW}-{SCREEN_HIGH}: below {(y < SCREEN_LOW).sum()}, above {(y > SCREEN_HIGH).sum()}")
within_sd = k.groupby("ClientID").LengthofCycle.std()
add(f"- Typical within-person SD of cycle length: median {within_sd.median():.1f} days "
    f"(people differ a lot; this is why history matters)")

# usable rows for "predict next cycle from previous cycles"
clean = k.drop_duplicates().sort_values(["ClientID", "CycleNumber"])
clean = clean.drop_duplicates(["ClientID", "CycleNumber"], keep="first")
counts = clean.groupby("ClientID").size()
for need in (2, 3, 4):
    rows = int(np.maximum(counts - need, 0).sum())
    ppl = int((counts > need).sum())
    add(f"- If a prediction needs {need} previous cycles: {rows} usable rows from {ppl} participants")

add()
add("### B5. Missing values")
miss = (k.isna().mean() * 100).round(1).sort_values(ascending=False)
miss.rename("percent_missing").to_frame().reset_index().rename(columns={"index": "column"}).to_csv(
    f"{OUT_DIR}/kaggle_missingness.csv", index=False)
add(f"- Columns with 0% missing: {(miss == 0).sum()}; with > 90% missing: {(miss > 90).sum()}")
add("- Complete columns: " + ", ".join(miss[miss == 0].index.tolist()))
first_only = []
for c in k.columns:
    if c in ("ClientID", "CycleNumber"):
        continue
    filled = k[k[c].notna()]
    # "participant-level" = filled only on the first cycle row of each participant
    if len(filled) > 0 and (filled.CycleNumber == 1).all() and miss[c] > 80:
        first_only.append(c)
add(f"- Participant-level columns filled ONLY on CycleNumber 1 (so ~9 of 10 rows are blank): "
    f"**{len(first_only)} columns**, e.g. {first_only[:10]}")
add("  Copying them down within the SAME participant would be legitimate (age/height do not change")
add("  within a study) but must be documented; it is not the same as inventing values.")
add("  Age is recorded for only 138 of 159 participants; those 21 stay missing (never guessed).")

age = k.groupby("ClientID").Age.max()
add()
add("### B6. Population")
add(f"- Age (participants with age recorded = {age.notna().sum()} of {k.ClientID.nunique()}): "
    f"min {age.min():.0f}, median {age.median():.0f}, mean {age.mean():.1f}, max {age.max():.0f}")
add(f"- Participants aged <= 24: {(age <= 24).sum()}; aged 18-22: {((age >= 18) & (age <= 22)).sum()}")
bmi = k.groupby("ClientID").BMI.max()
add(f"- BMI available for {bmi.notna().sum()} participants")

add()
add("### B7. Leakage warnings (columns that must NOT be inputs when predicting cycle length)")
chk = k.dropna(subset=["EstimatedDayofOvulation", "LengthofLutealPhase", "LengthofCycle"])
diff = (chk.EstimatedDayofOvulation + chk.LengthofLutealPhase - chk.LengthofCycle).abs()
add(f"- EstimatedDayofOvulation + LengthofLutealPhase equals LengthofCycle (within 1 day) in "
    f"**{(diff <= 1).mean() * 100:.0f}%** of {len(chk)} cycles -> they are the target in disguise.")
add("- MeanCycleLength is a per-participant average calculated from ALL cycles (including future ones).")
add("- Fertility-window columns (TotalDaysofFertility, FirstDayofHigh, ...) describe the SAME cycle that")
add("  is being predicted and are only known after it ends.")
add("- Intercourse / pregnancy-intent / contraceptive-method columns are fertility variables; they are")
add("  outside our app's purpose (no fertility or contraception advice) and are excluded by design.")

# ============================================================================
# 4. COMPATIBILITY
# ============================================================================
add()
add("---")
add("## PART C - Are the two datasets compatible for combined training?")
add()
comp = pd.DataFrame([
    ["Unit of observation", "1 row = 1 person", "1 row = 1 cycle of 1 person"],
    ["Participants", f"{len(cohort)} (cohort)", f"{k.ClientID.nunique()}"],
    ["Cycle information", "Up to 4 period START dates -> max 3 intervals", "Cycle length for many consecutive cycles (no dates)"],
    ["Age", f"{cohort.age_years.min()}-{cohort.age_years.max()}, median {cohort.age_years.median():.0f}",
     f"{age.min():.0f}-{age.max():.0f}, median {age.median():.0f}"],
    ["Bleeding duration", "Category (2-3, 4-5, 6-7, 8+ days)", "Exact days (LengthofMenses)"],
    ["Symptoms / diet / exercise / activity", "Yes (self-reported, categorical)", "No (only bleeding scores)"],
    ["BMI", "No", f"Only {bmi.notna().sum()} participants"],
    ["How cycles were recorded", "Recalled dates typed in a survey", "Appears to be prospective charting for fertility awareness (inferred from column names; confirm with codebook)"],
    ["Time window", f"About 4 months ({cohort.aligned_period_start_4.min().date()} to {cohort.raw_date_1.max().date()})", "Many cycles per person over a long period"],
], columns=["Aspect", "Primary survey", "Kaggle / FedCycle"])
add(table(comp, index=False))
add()
add("**Genuinely common variables:** age, cycle length, bleeding (length) duration. Nothing else is shared.")
add()
add("**Verdict (my reading of the numbers above):**")
add("1. Do NOT merge them row-by-row. Different unit of observation, different recording method,")
add("   and the primary survey cannot supply the multi-cycle history a sequence model needs.")
add("2. Kaggle/FedCycle is the only realistic TRAINING source for cycle-interval prediction, using")
add("   only features that exist in the app too (previous cycle lengths and simple summaries,")
add("   age if available). Participant-level split by ClientID.")
add("3. The primary survey is used for (a) describing the student population, (b) testing the")
add("   irregularity rules, (c) a tiny, clearly-labelled sanity check of the trained model.")
add("4. Population caveat: Kaggle participants are older on average and appear to have been charting for")
add("   fertility awareness; the primary survey is a small student sample. So the model must be")
add("   described as 'trained on an adult fertility-charting dataset', NOT 'trained on Indian")
add("   college students'.")

add()
add("---")
add("## PART D - Open questions for the project owner")
add("1. Send the Kaggle/FedCycle codebook (data dictionary).")
add("2. Primary survey: do you still have the original response/date format? Could the very short")
add("   intervals (1-10 days) come from end dates or a mixed-up date picker?")
add("3. The primary sheet name says 'Cycle_Cleaning' and the Read_Me says it is 'not fully")
add("   validated'. Please confirm which sheet you consider final.")

with open(f"{OUT_DIR}/data_quality_report.md", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(f"\nReport written to {OUT_DIR}/data_quality_report.md")
